"""Writes shaders/ntc_fast.glsl.

    python shaders/gen_ntc_fast.py          # rewrite the file
    python shaders/gen_ntc_fast.py --check  # exit 1 if the file is stale

Every index into a private array (features, layer input, packed input) is a
literal. A private array that is indexed by a loop variable lives in scratch
memory unless the compiler unrolls that loop, and AMD's compiler treats
[[unroll]] as a size-bounded hint, so the loop form put every array of the
decode in scratch on RDNA. Unused literal slots are behind guards such as
`if (17 < inn)` that fold at pipeline creation.

The one dynamic index left is the output row. Each layer runs a real loop of
4 rows per step with a uniform counter and writes its outputs to two private
arrays of at most 32 words (registers on AMD, see COMMON), or to workgroup
memory with NTC_FAST_LDS; the next layer reads them back with literal
indices. Fully
unrolling the rows as well removes that round trip, but 64 inlined copies of
a 160-slot row made pipeline creation take seconds on the AMD compiler and
minutes and gigabytes on Mesa.
"""

from __future__ import annotations

import sys
from pathlib import Path

MAX_IN = 160      # layer 0 inputs
MAX_HID = 64      # hidden width, and layer inputs after layer 0
MAX_OUT = 16      # output channels
MAX_GRIDS = 8
MAX_PLANES = 8    # channel planes per grid
MAX_PLANE_CH = 16  # channels per plane (32 bits / 2 bits)
MAX_LAYERS = 4
MAX_PEOCT = 16

OUT = Path(__file__).resolve().parent / "ntc_fast.glsl"

def max_in(l: int) -> int:
    return MAX_IN if l == 0 else MAX_HID


