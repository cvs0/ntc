COMMON = """
#define NTCF_MAX_IN {max_in}
#define NTCF_MAX_HID {max_hid}
#define NTCF_MAX_OUT {max_out}

layout(std140, set = 0, binding = 0) uniform NtcfParams {{ uvec4 ntcf_p[4096]; }};
layout(std430, set = 0, binding = 1) readonly buffer NtcfLatents {{ uint ntcf_l[]; }};

// Input of the current layer. Private, indexed by literals only.
float ntcf_x[NTCF_MAX_IN];
#ifdef NTC_FAST_FP16
f16vec2 ntcf_h[NTCF_MAX_IN / 2];  // packed fp16 layer input
#endif
#ifdef NTC_FAST_I8
uint ntcf_q[NTCF_MAX_IN / 4];     // packed int8 layer input (high bytes for 16-bit codes)
uint ntcf_q2[NTCF_MAX_IN / 4];    // low bytes of 16-bit codes
#ifdef NTC_FAST_I16
const bool NTCF_I16 = true;
#else
const bool NTCF_I16 = false;
#endif
#endif

// Layer outputs. The output row of the row loop is the one dynamic index of
// the decode. By default the rows are private and split into two arrays of
// at most 32: the AMD compiler keeps a private array of up to 32 words in
// registers under a dynamic index (v_movrel), and with uniform row counters
// it usually unrolls the loop and drops the index altogether. A 64-word array
// under a dynamic index would go to scratch. Sized for the widest layer,
// rounded up to the 4 rows of a loop step.
// fp16 and i8 store the outputs of packed hidden layers as two halves per
// word: fp16 rounds the next layer's input to fp16 anyway, i8 to 8-bit codes.
// That keeps the dynamically indexed part of fp16 and i8 within 32 words.
// NTC_FAST_LDS puts the rows in workgroup memory instead, one slice per
// invocation (no barrier). It needs no private dynamic index, for a driver
// that would spill one to scratch, but on RDNA4 the 8 to 16 KiB per
// workgroup caps occupancy at 4 to 8 waves per SIMD.
// Written with ?: rather than &&: glslang emits && on specialization
// constants as a branch, which is not a valid constant.
#if defined(NTC_FAST_FP16)
const bool NTCF_H1 = (NTCF_LAYERS > 1 ? NTCF_GS0 : 1) == 0;
const bool NTCF_H2 = (NTCF_LAYERS > 2 ? NTCF_GS1 : 1) == 0;
const bool NTCF_H3 = (NTCF_LAYERS > 3 ? NTCF_GS2 : 1) == 0;
#elif defined(NTC_FAST_I8) && !defined(NTC_FAST_I16)
const bool NTCF_H1 = (NTCF_LAYERS > 1 ? NTCF_GS0 & 3 : 1) == 0;
const bool NTCF_H2 = (NTCF_LAYERS > 2 ? NTCF_GS1 & 3 : 1) == 0;
const bool NTCF_H3 = (NTCF_LAYERS > 3 ? NTCF_GS2 & 3 : 1) == 0;
#else
const bool NTCF_H1 = false;
const bool NTCF_H2 = false;
const bool NTCF_H3 = false;
#endif
const int NTCF_R1 = ((NTCF_W1 + 3) & ~3) >> (NTCF_H1 ? 1 : 0);
const int NTCF_R2 = ((NTCF_W2 + 3) & ~3) >> (NTCF_H2 ? 1 : 0);
const int NTCF_R3 = ((NTCF_W3 + 3) & ~3) >> (NTCF_H3 ? 1 : 0);
const int NTCF_R4 = (NTCF_W4 + 3) & ~3;
const int NTCF_R12 = NTCF_R1 > NTCF_R2 ? NTCF_R1 : NTCF_R2;
const int NTCF_R34 = NTCF_R3 > NTCF_R4 ? NTCF_R3 : NTCF_R4;
const int NTCF_ROWS = NTCF_R12 > NTCF_R34 ? NTCF_R12 : NTCF_R34;
#ifdef NTC_FAST_LDS
#define NTCF_WG int(gl_WorkGroupSize.x * gl_WorkGroupSize.y * gl_WorkGroupSize.z)
shared uint ntcf_s[NTCF_ROWS * NTCF_WG];
void ntcf_st(int o, float v) {{ ntcf_s[o * NTCF_WG + int(gl_LocalInvocationIndex)] = floatBitsToUint(v); }}
float ntcf_ld(int o) {{ return uintBitsToFloat(ntcf_s[o * NTCF_WG + int(gl_LocalInvocationIndex)]); }}
void ntcf_st2(int o, uint v) {{ ntcf_s[o * NTCF_WG + int(gl_LocalInvocationIndex)] = v; }}
uint ntcf_ld2(int o) {{ return ntcf_s[o * NTCF_WG + int(gl_LocalInvocationIndex)]; }}
#else
float ntcf_oa[NTCF_ROWS < 32 ? NTCF_ROWS : 32];
float ntcf_ob[NTCF_ROWS > 32 ? NTCF_ROWS - 32 : 1];
void ntcf_st(int o, float v) {{ if (o < 32) ntcf_oa[o] = v; else ntcf_ob[o - 32] = v; }}
float ntcf_ld(int o) {{ return o < 32 ? ntcf_oa[o] : ntcf_ob[o - 32]; }}
void ntcf_st2(int o, uint v) {{ ntcf_st(o, uintBitsToFloat(v)); }}
uint ntcf_ld2(int o) {{ return floatBitsToUint(ntcf_ld(o)); }}
#endif

uint ntcf_pu(int i) {{ return ntcf_p[i >> 2][i & 3]; }}
float ntcf_pf(int i) {{ return uintBitsToFloat(ntcf_pu(i)); }}

int ntcf_gc(int g) {{
    return g == 0 ? NTCF_GC0 : g == 1 ? NTCF_GC1 : g == 2 ? NTCF_GC2 : g == 3 ? NTCF_GC3
         : g == 4 ? NTCF_GC4 : g == 5 ? NTCF_GC5 : g == 6 ? NTCF_GC6 : NTCF_GC7;
}}
int ntcf_gb(int g) {{
    return g == 0 ? NTCF_GB0 : g == 1 ? NTCF_GB1 : g == 2 ? NTCF_GB2 : g == 3 ? NTCF_GB3
         : g == 4 ? NTCF_GB4 : g == 5 ? NTCF_GB5 : g == 6 ? NTCF_GB6 : NTCF_GB7;
}}

// Largest power of two <= n, capped at 32 / bits. Matches ntc::fast_planes.
int ntcf_plane_n(int rem, int bits) {{
    int n = rem >= 16 ? 16 : rem >= 8 ? 8 : rem >= 4 ? 4 : rem >= 2 ? 2 : 1;
    return min(n, 32 / bits);
}}

#ifdef NTC_FAST_EXACT
#define NTCF_P precise
precise float ntcf_lerp(float a, float b, float t) {{ precise float d = (b - a) * t; precise float r = a + d; return r; }}
precise float ntcf_mad(float acc, float w, float x) {{ precise float p = w * x; precise float r = acc + p; return r; }}
// r + s * acc, rounded twice
precise float ntcf_sadd(float r, float s, float acc) {{ precise float p = s * acc; precise float q = r + p; return q; }}
#else
#define NTCF_P
float ntcf_lerp(float a, float b, float t) {{ return fma(b - a, t, a); }}
float ntcf_mad(float acc, float w, float x) {{ return fma(w, x, acc); }}
float ntcf_sadd(float r, float s, float acc) {{ return fma(s, acc, r); }}
#endif

// One latent record at texel (x, y) of a plane. R is a constant.
uint ntcf_rec(uint row, int x, int R) {{
    uint bit = uint(x) * uint(R);
    uint w = ntcf_l[row + (bit >> 5u)];
    return R == 32 ? w : bitfieldExtract(w, int(bit & 31u), R);
}}

float ntcf_activate(float y) {{
    float z;
    if (NTCF_ACT == 1) {{
        z = max(y, 0.0);
    }} else if (NTCF_ACT == 2) {{
        z = min(y, 3.0) * clamp(y * (1.0 / 3.0) + 0.5, 0.0, 1.0);
    }} else {{
        z = y;
    }}
    if (NTCF_REQUANT != 0) z = clamp(round(z * 80.0 - 113.0), -128.0, 127.0);
    return z;
}}

float ntcf_fin(bool last, float r) {{ return last ? r : ntcf_activate(r); }}

#ifdef NTC_FAST_FP16
f16vec2 ntcf_hmac(f16vec2 a, uint w, f16vec2 h) {{ return fma(unpackFloat2x16(w), h, a); }}
float ntcf_hsum(f16vec2 a) {{ return float(a.x) + float(a.y); }}
#endif

#ifdef NTC_FAST_I8
int ntcf_qi(float x, float s, float rs, int lo, int hi) {{
    return clamp(int(round(NTCF_ACTI8 != 0 ? x / s : x * rs)), lo, hi);
}}
// Low bytes of four codes, byte b from code b.
uint ntcf_pk(int a, int b, int c, int d) {{
    return (uint(a) & 255u) | ((uint(b) & 255u) << 8) | ((uint(c) & 255u) << 16) | (uint(d) << 24);
}}
#endif
"""


def gen_grid() -> list[str]:
    o = []
    o.append("// Features of grid g (a literal at every call): bilinear latents at mip km,")
    o.append("// dequantized, written to ntcf_x[n0 ...].")
    o.append("void ntcf_grid(int g, vec2 u, int km, int n0, int ls0) {")
    o.append("    const int C = ntcf_gc(g);")
    o.append("    const int bits = ntcf_gb(g);")
    o.append("    uvec4 md = ntcf_p[g * 8 + km];")
    o.append("    int GW = int(md.y), GH = int(md.z);")
    o.append("    NTCF_P float fx = u.x * float(GW) - 0.5;")
    o.append("    NTCF_P float fy = u.y * float(GH) - 0.5;")
    o.append("    int x0 = int(floor(fx));")
    o.append("    int y0 = int(floor(fy));")
    o.append("    float tx = fx - float(x0);")
    o.append("    float ty = fy - float(y0);")
    o.append("    int xa = x0 < 0 ? x0 + GW : x0;")
    o.append("    int xb = x0 + 1 >= GW ? x0 + 1 - GW : x0 + 1;")
    o.append("    int ya = y0 < 0 ? y0 + GH : y0;")
    o.append("    int yb = y0 + 1 >= GH ? y0 + 1 - GH : y0 + 1;")
    o.append("    float mid = float((1 << bits) - 1) * 0.5;")
    o.append("    uint pbase = md.x;")
    o.append("    int c = 0;")
    o.append("    int pn, R, rw;")
    o.append("    uint ra, rb, r00, r01, r10, r11;")
    for p in range(MAX_PLANES):
        o.append(f"    // plane {p}")
        o.append("    if (c < C) {")
        o.append("        pn = ntcf_plane_n(C - c, bits);")
        o.append("        R = pn * bits;")
        o.append("        rw = (GW * R + 31) >> 5;")
        o.append("        ra = pbase + uint(ya * rw);")
        o.append("        rb = pbase + uint(yb * rw);")
        o.append("        r00 = ntcf_rec(ra, xa, R); r01 = ntcf_rec(ra, xb, R);")
        o.append("        r10 = ntcf_rec(rb, xa, R); r11 = ntcf_rec(rb, xb, R);")
        for k in range(MAX_PLANE_CH):
            o.append(f"        if ({k} < pn) ntcf_tap(r00, r01, r10, r11, {k} * bits, bits, tx, ty, mid,"
                     f" n0 + c + {k}, ls0 + c + {k});")
        o.append("        c += pn;")
        o.append("        pbase += uint(rw * GH);")
        o.append("    }")
    o.append("}")
    return o


TAP = """
// One channel of one plane: bilinear lerp of the four taps, dequantized.
// i (the feature slot) is a constant after inlining.
void ntcf_tap(uint r00, uint r01, uint r10, uint r11, int sh, int bits, float tx, float ty, float mid,
              int i, int si) {
    float c00 = float(bitfieldExtract(r00, sh, bits));
    float c01 = float(bitfieldExtract(r01, sh, bits));
    float c10 = float(bitfieldExtract(r10, sh, bits));
    float c11 = float(bitfieldExtract(r11, sh, bits));
    float a = ntcf_lerp(c00, c01, tx);
    float b = ntcf_lerp(c10, c11, tx);
    float l = ntcf_lerp(a, b, ty);
    ntcf_x[i] = (l - mid) * ntcf_pf(si);
}
"""


def gen_pe() -> list[str]:
    o = ["// Positional terms after the latent features, at ntcf_x[n ...].",
         "void ntcf_pe(vec2 uv, int mip, int n) {",
         "    if (NTCF_PE == 1) {",
         "        const float tau = 6.283185307179586;"]
    for k in range(MAX_PEOCT):
        o.append(f"        if ({k} < NTCF_PEOCT) {{")
        o.append(f"            float f = {float(1 << k):.1f};")
        o.append("            NTCF_P float au = tau * uv.x * f;")
        o.append("            NTCF_P float av = tau * uv.y * f;")
        o.append(f"            ntcf_x[n + {4 * k}] = sin(au);")
        o.append(f"            ntcf_x[n + {4 * k + 1}] = cos(au);")
        o.append(f"            ntcf_x[n + {4 * k + 2}] = sin(av);")
        o.append(f"            ntcf_x[n + {4 * k + 3}] = cos(av);")
        o.append("        }")
    o.append("    } else if (NTCF_PE == 2 && NTCF_PEOCT > 0) {")
    o.append("        vec2 p = uv;")
    for k in range(MAX_PEOCT):
        o.append(f"        if ({k} < NTCF_PEOCT) {{")
        o.append("            NTCF_P float t0 = (p.x - floor(p.x)) * 2.0 - 1.0;")
        o.append("            NTCF_P float t1 = (p.y - floor(p.y)) * 2.0 - 1.0;")
        o.append("            NTCF_P float t2 = ((p.x + 0.25) - floor(p.x + 0.25)) * 2.0 - 1.0;")
        o.append("            NTCF_P float t3 = ((p.y + 0.25) - floor(p.y + 0.25)) * 2.0 - 1.0;")
        o.append(f"            ntcf_x[n + {4 * k}] = t0;")
        o.append(f"            ntcf_x[n + {4 * k + 1}] = t1;")
        o.append(f"            ntcf_x[n + {4 * k + 2}] = t2;")
        o.append(f"            ntcf_x[n + {4 * k + 3}] = t3;")
        o.append("            p *= 2.0;")
        o.append("        }")
    o.append("        float lod = float(mip) / float(max(NTCF_NUMMIPS - 1, 1));")
    o.append("        ntcf_x[n + 4 * NTCF_PEOCT] = lod;")
    o.append("        ntcf_x[n + 4 * NTCF_PEOCT + 1] = lod;")
    o.append("    }")
    o.append("}")
    return o


R = 4  # output rows per loop iteration; the host pads every layer to a multiple of R rows


def gen_layer(l: int) -> list[str]:
    """Layer l: the input is in ntcf_x (literal indices), each output row is
    written with ntcf_st (private rows, or ntcf_s with NTC_FAST_LDS). The
    row loop is a real loop with a uniform counter; every array index inside
    it is a literal."""
    n = max_in(l)
    rr = range(R)
    o: list[str] = []

    # act_int8 requant of the input, in place
    o.append(f"void ntcf_requant{l}() {{")
    o.append(f"    const int inn = NTCF_W{l};")
    o.append(f"    float s = max(ntcf_pf(NTCF_ASOFF + {l}), 1e-6);")
    for i in range(n):
        o.append(f"    if ({i} < inn) ntcf_x[{i}] = clamp(round(ntcf_x[{i}] / s), -127.0, 127.0) * s;")
    o.append("}")
    o.append("")

    # fp32, one group per row. Weights [outp][4 * in4]: row o + r starts r * in4 uvec4s later.
    o.append(f"// Layer {l}, fp32, one group per row.")
    o.append(f"void ntcf_rows{l}() {{")
    o += LAYER_CONSTS(l)
    o.append("    for (int o = 0; o < outn; o += 4) {")
    o.append(f"        const int wb = (NTCF_WO{l} >> 2) + o * in4;")
    o.append("        " + " ".join(f"float a{r} = 0.0;" for r in rr))
    o.append("        uvec4 w;")
    for k in range(n // 4):
        o.append(f"        if ({4 * k} < inn) {{")
        for r in rr:
            o.append(f"            w = ntcf_p[wb + {r} * in4 + {k}];")
            for b in range(4):
                i = 4 * k + b
                mac = f"a{r} = ntcf_mad(a{r}, uintBitsToFloat(w[{b}]), ntcf_x[{i}]);"
                o.append(f"            {mac}" if b == 0 else f"            if ({i} < inn) {mac}")
        o.append("        }")
    o.append(f"        vec4 bias = uintBitsToFloat(ntcf_p[(NTCF_BO{l} >> 2) + (o >> 2)]);")
    for r in rr:
        o.append(f"        ntcf_st(o + {r}, ntcf_fin(last, ntcf_sadd(bias[{r}], ntcf_pf(NTCF_SO{l} + (o + {r}) * ng), a{r})));")
    o.append("    }")
    o.append("}")
    o.append("")

    # fp32 grouped: r = bias, then r += scale[g] * dot over group g.
    # gd stands in for gs as a divisor: specialization constant expressions
    # are evaluated on both sides of a branch, so nothing may divide by gs.
    o.append(f"// Layer {l}, fp32, grouped rows.")
    o.append(f"void ntcf_grows{l}() {{")
    o += LAYER_CONSTS(l)
    o.append("    for (int o = 0; o < outn; o += 4) {")
    o.append(f"        const int wb = (NTCF_WO{l} >> 2) + o * in4;")
    o.append(f"        vec4 bias = uintBitsToFloat(ntcf_p[(NTCF_BO{l} >> 2) + (o >> 2)]);")
    o.append("        " + " ".join(f"float r{r} = bias[{r}];" for r in rr))
    o.append("        " + " ".join(f"float a{r} = 0.0;" for r in rr))
    o.append("        uvec4 w;")
    for k in range(n // 4):
        o.append(f"        if ({4 * k} < inn) {{")
        for r in rr:
            o.append(f"            w = ntcf_p[wb + {r} * in4 + {k}];")
            for b in range(4):
                i = 4 * k + b
                o.append(f"            if ({i} < inn && {i} / gd < ng) {{ a{r} = ntcf_mad(a{r}, uintBitsToFloat(w[{b}]), ntcf_x[{i}]);"
                         f" if ({i + 1} == inn || {i + 1} % gd == 0) {{"
                         f" r{r} = ntcf_sadd(r{r}, ntcf_pf(NTCF_SO{l} + (o + {r}) * ng + {i} / gd), a{r}); a{r} = 0.0; }} }}")
        o.append("        }")
    for r in rr:
        o.append(f"        ntcf_st(o + {r}, ntcf_fin(last, r{r}));")
    o.append("    }")
    o.append("}")
    o.append("")

    # fp16: weights [outp][8 * in8] halves, one uvec4 per 8 inputs.
    o.append("#ifdef NTC_FAST_FP16")
    o.append(f"// Layer {l}, packed fp16, one group per row.")
    o.append(f"void ntcf_hrows{l}() {{")
    o += LAYER_CONSTS(l)
    for j in range(n // 2):
        o.append(f"    if ({2 * j} < inn) ntcf_h[{j}] = f16vec2(ntcf_x[{2 * j}], {2 * j + 1} < inn ? ntcf_x[{2 * j + 1}] : 0.0);")
    o.append("    for (int o = 0; o < outn; o += 4) {")
    o.append(f"        const int hb = (NTCF_HO{l} >> 2) + o * in8;")
    o.append("        " + " ".join(f"f16vec2 a{r} = f16vec2(0.0);" for r in rr))
    o.append("        uvec4 w;")
    for k in range(n // 8):
        o.append(f"        if ({8 * k} < inn) {{")
        for r in rr:
            o.append(f"            w = ntcf_p[hb + {r} * in8 + {k}];")
            for b in range(4):
                j = 4 * k + b
                mac = f"a{r} = ntcf_hmac(a{r}, w[{b}], ntcf_h[{j}]);"
                o.append(f"            {mac}" if b == 0 else f"            if ({2 * j} < inn) {mac}")
        o.append("        }")
    o.append(f"        vec4 bias = uintBitsToFloat(ntcf_p[(NTCF_BO{l} >> 2) + (o >> 2)]);")
    o.append(f"        vec4 scl = uintBitsToFloat(ntcf_p[(NTCF_SO{l} >> 2) + (o >> 2)]);")
    for r in rr:
        o.append(f"        float v{r} = ntcf_fin(last, bias[{r}] + scl[{r}] * ntcf_hsum(a{r}));")
    o += STORE4("last", "v")
    o.append("    }")
    o.append("}")
    o.append("#endif")
    o.append("")

    # i8: weights [outp][16 * in16] int8, one uvec4 per 16 inputs.
    o.append("#ifdef NTC_FAST_I8")
    o.append(f"// Layer {l}, int8 dot, grouped or not (group % 4 == 0).")
    o.append(f"void ntcf_qrows{l}() {{")
    o += LAYER_CONSTS(l)
    # Activation codes. act_int8 files: the file's scale, signed int8, the
    # same codes the network was trained with. Otherwise a per-vector
    # max-abs scale: layer 0 is split into a signed high byte and an
    # unsigned low byte (16-bit codes, two dots per 4 inputs; latents and
    # positional terms are signed and few), and a layer whose input is a ReLU
    # output uses unsigned 8-bit codes (twice the levels of signed codes).
    # NTC_FAST_I16 uses 16-bit codes on every layer.
    w16 = "NTCF_ACTI8 == 0" if l == 0 else "NTCF_I16 && NTCF_ACTI8 == 0"
    o.append(f"    const bool w16 = {w16};")
    o.append(f"    const bool uns = {'false' if l == 0 else '!w16 && NTCF_ACTI8 == 0 && NTCF_ACT == 1 && NTCF_REQUANT == 0'};")
    o.append("    const int qmax = w16 ? 32767 : uns ? 255 : 127;")
    o.append("    const int qmin = uns ? 0 : -qmax;")
    o.append("    float s;")
    o.append("    if (NTCF_ACTI8 != 0) {")
    o.append(f"        s = max(ntcf_pf(NTCF_ASOFF + {l}), 1e-6);")
    o.append("    } else {")
    o.append("        float m = 0.0;")
    for i in range(n):
        o.append(f"        if ({i} < inn) m = max(m, abs(ntcf_x[{i}]));")
    o.append("        s = max(m / float(qmax), 1e-20);")
    o.append("    }")
    o.append("    float rs = 1.0 / s;")
    for j in range(n // 4):
        o.append(f"    if ({4 * j} < inn) {{")
        for b in range(4):
            i = 4 * j + b
            o.append(f"        int c{b} = {i} < inn ? ntcf_qi(ntcf_x[{i}], s, rs, qmin, qmax) : 0;")
        o.append(f"        ntcf_q[{j}] = w16 ? ntcf_pk(c0 >> 8, c1 >> 8, c2 >> 8, c3 >> 8) : ntcf_pk(c0, c1, c2, c3);")
        o.append(f"        if (w16) ntcf_q2[{j}] = ntcf_pk(c0, c1, c2, c3);")
        o.append("    }")
    o.append("    for (int o = 0; o < outn; o += 4) {")
    o.append(f"        const int qb = (NTCF_QO{l} >> 2) + o * in16;")
    o.append(f"        vec4 bias = uintBitsToFloat(ntcf_p[(NTCF_BO{l} >> 2) + (o >> 2)]);")
    o.append("        " + " ".join(f"float r{r} = bias[{r}];" for r in rr))
    o.append("        " + " ".join(f"int a{r} = 0;" for r in rr))
    o.append("        " + " ".join(f"int h{r} = 0;" for r in rr))
    o.append("        uvec4 w;")
    # Weights are signed. dotPacked4x8EXT(int, int) is the signed dot,
    # (int, uint) the signed by unsigned dot; (uint, uint) would be unsigned.
    for k in range(n // 16):
        o.append(f"        if ({16 * k} < inn) {{")
        for r in rr:
            o.append(f"            w = ntcf_p[qb + {r} * in16 + {k}];")
            for b in range(4):
                j = 4 * k + b
                dot = (f"if (w16) {{ h{r} += dotPacked4x8EXT(int(w[{b}]), int(ntcf_q[{j}]));"
                       f" a{r} += dotPacked4x8EXT(int(w[{b}]), ntcf_q2[{j}]); }}"
                       f" else if (uns) a{r} += dotPacked4x8EXT(int(w[{b}]), ntcf_q[{j}]);"
                       f" else a{r} += dotPacked4x8EXT(int(w[{b}]), int(ntcf_q[{j}]));")
                o.append(f"            if ({4 * j} < inn && (gs == 0 || {4 * j} / gd < ng)) {{ {dot}"
                         f" if ({4 * j + 4} >= inn || (gs != 0 && {4 * j + 4} % gd == 0)) {{"
                         f" r{r} += ntcf_pf(NTCF_SO{l} + (o + {r}) * ng + (gs == 0 ? 0 : {4 * j} / gd))"
                         f" * (float((h{r} << 8) + a{r}) * s); a{r} = 0; h{r} = 0; }} }}")
        o.append("        }")
    for r in rr:
        o.append(f"        r{r} = ntcf_fin(last, r{r});")
    o += STORE4("last || NTCF_I16", "r")
    o.append("    }")
    o.append("}")
    o.append("#endif")
    o.append("")

    # layer driver
    o.append(f"void ntcf_layer{l}() {{")
    o += LAYER_CONSTS(l)
    if l > 0:
        o.append(f"    if (NTCF_H{l}) {{")
        for i in range(0, n, 2):
            o.append(f"        if ({i} < inn) {{ vec2 v = unpackHalf2x16(ntcf_ld2({i // 2})); ntcf_x[{i}] = v.x; ntcf_x[{i + 1}] = v.y; }}")
        o.append("    } else {")
        for i in range(n):
            o.append(f"        if ({i} < inn) ntcf_x[{i}] = ntcf_ld({i});")
        o.append("    }")
    o.append("#ifdef NTC_FAST_I8")
    o.append(f"    if ((gs & 3) == 0) {{ ntcf_qrows{l}(); return; }}")
    o.append("#endif")
    o.append(f"    if (NTCF_ACTI8 != 0) ntcf_requant{l}();")
    o.append("#ifdef NTC_FAST_FP16")
    o.append(f"    if (gs == 0) ntcf_hrows{l}(); else ntcf_grows{l}();")
    o.append("#else")
    o.append(f"    if (gs == 0) ntcf_rows{l}(); else ntcf_grows{l}();")
    o.append("#endif")
    o.append("}")
    return o


def STORE4(full: str, v: str) -> list[str]:
    # Rows o..o+3 to the layer outputs: fp32 if `full`, else two halves per
    # word (read back by the next layer when its NTCF_H flag is set).
    return [f"        if ({full}) {{",
            *[f"            ntcf_st(o + {r}, {v}{r});" for r in range(4)],
            "        } else {",
            f"            ntcf_st2(o >> 1, packHalf2x16(vec2({v}0, {v}1)));",
            f"            ntcf_st2((o >> 1) + 1, packHalf2x16(vec2({v}2, {v}3)));",
            "        }"]


def LAYER_CONSTS(l: int) -> list[str]:
    return [f"    const int inn = NTCF_W{l};",
            f"    const int outn = NTCF_W{l + 1};",
            f"    const int gs = NTCF_GS{l};",
            f"    const int ng = NTCF_NG{l};",
            "    const int gd = gs == 0 ? 1 : gs;",
            "    const int in4 = (inn + 3) >> 2;",
            "    const int in8 = (inn + 7) >> 3;",
            "    const int in16 = (inn + 15) >> 4;",
            f"    const bool last = NTCF_LAYERS == {l + 1};"]


def gen_eval() -> list[str]:
    o = ["// Full decode at one mip. Read the result with ntcf_y.",
         "void ntcf_eval(vec2 uv, int mip) {",
         "    vec2 u = uv - floor(uv);  // exact for uv in [0, 1); same taps as the integer wrap",
         "    int km = min(mip, 7);",
         "    int n = 0;"]
    for g in range(MAX_GRIDS):
        o.append(f"    if ({g} < NTCF_GRIDS) {{ ntcf_grid({g}, u, km, n, NTCF_LSOFF + n); n += NTCF_GC{g}; }}")
    o.append("    ntcf_pe(uv, mip, n);")
    for l in range(MAX_LAYERS):
        o.append(f"    if ({l} < NTCF_LAYERS) ntcf_layer{l}();")
    o.append("}")
    o.append("")
    o.append("// Output channel c of the last ntcf_eval, c < NTCF_OUTCH.")
    o.append("float ntcf_y(int c) { return ntcf_ld(c); }")
    return o


def generate() -> str:
    lines = [HEADER]
    for i, name in enumerate(SPEC):
        lines.append(f"layout(constant_id = {i}) const int NTCF_{name} = {SPEC_DEFAULT.get(name, 0)};")
    lines.append(COMMON.format(max_in=MAX_IN, max_hid=MAX_HID, max_out=MAX_OUT))
    lines.append(TAP)
    lines += gen_grid()
    lines.append("")
    lines += gen_pe()
    lines.append("")
    for l in range(MAX_LAYERS):
        lines += gen_layer(l)
        lines.append("")
    lines += gen_eval()
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; run python shaders/gen_ntc_fast.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
